import { useEffect, useMemo, useState, lazy, Suspense } from 'react';
import { ChefHat, Smartphone } from 'lucide-react';
import { AnimatePresence, MotionConfig } from 'framer-motion';
import { useShallow } from 'zustand/react/shallow';
import { KitchenView } from './views/KitchenView';
import { DiscoverView } from './views/DiscoverView';
import { CookbookView } from './views/CookbookView';
import { CookingView } from './views/CookingView';
import { BottomNav } from './components/BottomNav';
import { RecipesProvider } from './context/RecipesContext';
import { sanitizeRecipes } from './lib/recipeValidation';
import { useAppStore, syncAcrossTabs } from './store/appStore';
import { useRoute } from './hooks/useRoute';
import { useDeviceSync } from './hooks/useDeviceSync';

// Overlays load on first use to keep the initial bundle small.
const RecipeDetail = lazy(() => import('./components/RecipeDetail').then((m) => ({ default: m.RecipeDetail })));
const CookingStepsView = lazy(() => import('./views/CookingStepsView').then((m) => ({ default: m.CookingStepsView })));
const FilterSheet = lazy(() => import('./components/FilterSheet').then((m) => ({ default: m.FilterSheet })));
const SyncSheet = lazy(() => import('./components/SyncSheet').then((m) => ({ default: m.SyncSheet })));
const PantrySheet = lazy(() => import('./components/PantrySheet').then((m) => ({ default: m.PantrySheet })));

export default function App() {
  const { route, setView, openDetail, startCooking, closeOverlay } = useRoute();
  const { pantry, myAiRecipes, communityRecipes, setCommunityRecipes, addToMaking, markCooked } = useAppStore(
    useShallow((s) => ({
      pantry: s.pantry, myAiRecipes: s.myAiRecipes, communityRecipes: s.communityRecipes,
      setCommunityRecipes: s.setCommunityRecipes, addToMaking: s.addToMaking, markCooked: s.markCooked,
    })),
  );
  const [showFilters, setShowFilters] = useState(false);
  const [showPantry, setShowPantry] = useState(false);
  // A scanned sync QR opens the app at /?sync=CODE.
  const [syncInvite] = useState(() => new URLSearchParams(window.location.search).get('sync'));
  const [showSync, setShowSync] = useState(() => syncInvite !== null);
  const syncStatus = useAppStore((s) => s.syncStatus);

  useDeviceSync();
  useEffect(() => {
    if (!syncInvite) return;
    const url = new URL(window.location.href);
    url.searchParams.delete('sync');
    window.history.replaceState(window.history.state, '', url);
  }, [syncInvite]);

  useEffect(() => syncAcrossTabs(), []);

  // Fetch community AI recipes generated by all users
  useEffect(() => {
    fetch('/api/community-recipes')
      .then((r) => (r.ok ? r.json() : []))
      .then((data: unknown) => {
        // Older deployments return a bare array; newer ones { recipes, upvotes }.
        const body = (Array.isArray(data) ? { recipes: data } : data ?? {}) as { recipes?: unknown; upvotes?: unknown };
        const upvotes = body.upvotes && typeof body.upvotes === 'object'
          ? Object.fromEntries(Object.entries(body.upvotes).map(([k, v]) => [Number(k), Number(v) || 0]))
          : {};
        setCommunityRecipes(sanitizeRecipes(body.recipes), upvotes);
      })
      .catch(() => { /* non-fatal */ });
  }, [setCommunityRecipes]);

  const aiRecipes = useMemo(() => [...myAiRecipes, ...communityRecipes], [myAiRecipes, communityRecipes]);

  const cookNow = (id: number) => {
    addToMaking(id);
    startCooking(id);
  };

  return (
    <MotionConfig reducedMotion="user">
    <RecipesProvider extra={aiRecipes}>
    <div
      className="min-h-screen w-full"
      style={{ background: 'linear-gradient(180deg, var(--bg-page) 0%, var(--bg-soft) 100%)' }}
    >
      <div
        className="max-w-[480px] mx-auto min-h-screen flex flex-col relative font-body"
        style={{ background: 'var(--bg-page)' }}
      >
        {/* Brand header */}
        <header className="px-6 pt-7 pb-2 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div
              className="w-9 h-9 rounded-xl bg-[var(--brand-500)] flex items-center justify-center"
              style={{ boxShadow: '0 6px 14px -3px rgba(var(--brand-rgb),0.5)' }}
            >
              <ChefHat size={20} className="text-white" strokeWidth={2.5} />
            </div>
            <div>
              <p className="font-display font-bold text-[var(--text-primary)] text-[18px] leading-none tracking-tight">
                Easy Peasy
              </p>
              <p className="font-display italic text-[var(--brand-500)] text-[14px] leading-none -mt-0.5">
                Recipe-sy
              </p>
            </div>
          </div>
          <div className="flex items-center gap-3">
          {pantry.length > 0 && route.view !== 'kitchen' && (
            <button
              onClick={() => setShowPantry(true)}
              className="text-[12px] font-body font-medium text-[var(--text-tertiary)] underline underline-offset-2"
            >
              {pantry.length} ingredients
            </button>
          )}
            <button
              onClick={() => setShowSync(true)}
              aria-label={syncStatus === 'off' ? 'Sync across devices' : `Device sync (${syncStatus === 'error' ? 'error' : 'on'})`}
              className="relative w-9 h-9 rounded-full bg-[var(--surface-cream)] flex items-center justify-center active:scale-90 transition-transform"
            >
              <Smartphone size={16} strokeWidth={2.4} className="text-[var(--text-secondary)]" aria-hidden="true" />
              {syncStatus !== 'off' && (
                <span aria-hidden="true" className="absolute top-1 right-1 w-2 h-2 rounded-full"
                  style={{ background: syncStatus === 'error' ? 'var(--brand-500)' : 'var(--success-500)' }} />
              )}
            </button>
          </div>
        </header>

        <main className="flex-1 flex flex-col">
          {route.view === 'kitchen' && <KitchenView onContinue={() => setView('discover')} />}
          {route.view === 'discover' && (
            <DiscoverView
              onOpenFilters={() => setShowFilters(true)}
              openDetail={openDetail}
              onCookNow={cookNow}
            />
          )}
          {route.view === 'cookbook' && <CookbookView openDetail={openDetail} onCookNow={cookNow} />}
          {route.view === 'making' && <CookingView openDetail={openDetail} onCookNow={startCooking} />}
        </main>

        <BottomNav view={route.view} setView={setView} />

        <Suspense fallback={null}>
          <AnimatePresence>
            {showFilters && <FilterSheet onClose={() => setShowFilters(false)} />}
          </AnimatePresence>

          {route.detailId !== null && (
            <RecipeDetail recipeId={route.detailId} onClose={closeOverlay} onCookNow={cookNow} />
          )}

          <AnimatePresence>
            {showPantry && (
              <PantrySheet
                onClose={() => setShowPantry(false)}
                onGoToKitchen={() => { setShowPantry(false); setView('kitchen'); }}
              />
            )}
          </AnimatePresence>

          <AnimatePresence>
            {showSync && <SyncSheet onClose={() => setShowSync(false)} initialCode={syncInvite} />}
          </AnimatePresence>

          <AnimatePresence>
            {route.cookId !== null && (
              <CookingStepsView
                key={route.cookId}
                recipeId={route.cookId}
                onClose={closeOverlay}
                onDone={() => {
                  if (route.cookId !== null) markCooked(route.cookId);
                  closeOverlay();
                }}
              />
            )}
          </AnimatePresence>
        </Suspense>
      </div>
    </div>
    </RecipesProvider>
    </MotionConfig>
  );
}
