import { useState } from 'react';
import { ThumbsUp, Flag } from 'lucide-react';
import { useAppStore, type Vote } from '../store/appStore';
import { AI_ID_BASE } from '../lib/recipeValidation';

/** Upvote / report controls for AI-generated community recipes. Renders nothing for built-ins. */
export function CommunityVote({ recipeId }: { recipeId: number }) {
  const vote = useAppStore((s) => s.votes[recipeId]);
  const setVote = useAppStore((s) => s.setVote);
  const upvotes = useAppStore((s) => s.communityUpvotes[recipeId] ?? 0);
  const [error, setError] = useState<string | null>(null);

  if (recipeId < AI_ID_BASE) return null;

  const send = async (v: Vote) => {
    if (vote) return;
    setError(null);
    setVote(recipeId, v); // optimistic; one vote per device
    try {
      const res = await fetch('/api/community-vote', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: recipeId, vote: v }),
      });
      if (!res.ok && res.status !== 409) throw new Error();
    } catch {
      setError("Couldn't send that — check your connection.");
    }
  };

  return (
    <div className="mb-7">
      <h2 className="font-display font-semibold text-[var(--text-primary)] text-[22px] mb-1">Community recipe</h2>
      <p className="font-body text-[13px] text-[var(--text-secondary)] mb-3">
        Generated by AI for another cook. Good ones get shown to more people.
      </p>
      <div className="flex gap-2">
        <button
          onClick={() => send('up')}
          disabled={!!vote}
          aria-pressed={vote === 'up'}
          className="flex items-center gap-1.5 px-4 py-2 rounded-full font-body text-[13px] font-semibold active:scale-95 transition-all disabled:cursor-default"
          style={{ background: vote === 'up' ? 'var(--success-100)' : 'var(--surface-cream)', color: vote === 'up' ? 'var(--success-700)' : 'var(--text-primary)' }}
        >
          <ThumbsUp size={14} strokeWidth={2.5} aria-hidden="true" />
          {vote === 'up' ? 'Thanks!' : 'Worked for me'}
          {upvotes + (vote === 'up' ? 1 : 0) > 0 && <span className="tabular-nums opacity-70">· {upvotes + (vote === 'up' ? 1 : 0)}</span>}
        </button>
        <button
          onClick={() => send('report')}
          disabled={!!vote}
          aria-pressed={vote === 'report'}
          className="flex items-center gap-1.5 px-4 py-2 rounded-full font-body text-[13px] font-semibold active:scale-95 transition-all disabled:cursor-default"
          style={{ background: 'var(--surface-cream)', color: vote === 'report' ? 'var(--brand-500)' : 'var(--text-secondary)' }}
        >
          <Flag size={14} strokeWidth={2.5} aria-hidden="true" />
          {vote === 'report' ? 'Reported' : 'Report'}
        </button>
      </div>
      {error && <p role="alert" className="font-body text-[12px] text-red-600 mt-2">{error}</p>}
    </div>
  );
}
